"""Reproduce Phase 7 verification using only disposable databases/archives.

Run: python scripts/verify_phase7.py
Writes PHASE7_VERIFICATION.md; never connects to X or changes application data.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import zipfile
from dataclasses import asdict, is_dataclass
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from exitvector_agent.audience import AudienceQueryService, DatabaseXAudienceDataProvider, MockXAudienceDataProvider, XArchiveImportService
from exitvector_agent.audience_archive import XArchiveAdapter
from exitvector_agent.database import Database, ensure_schema


def default(value):
    return asdict(value) if is_dataclass(value) else value.isoformat()


def json_block(value):
    return "```json\n" + json.dumps(value, default=default, indent=2) + "\n```"


def table(headers, rows):
    return "\n".join(["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|",
                      *["| " + " | ".join(str(v).replace("|", "/").replace("\n", " ") for v in row) + " |" for row in rows]])


def counts(db):
    return {name: db.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
            for name in sorted(db.list_tables()) if name.startswith("audience_")}


def state(db):
    return {name: [tuple(r) for r in db.execute(f"SELECT * FROM {name} ORDER BY rowid")]
            for name in sorted(db.list_tables()) if name.startswith("audience_") or name == "configuration"}


def main():
    report = ["# Phase 7 remediation verification", "Generated by `python scripts/verify_phase7.py`.",
              "Mock reference: 2026-06-30 UTC; default window: all. All imports/CLI probes use disposable databases."]
    provider = MockXAudienceDataProvider()
    service = AudienceQueryService(provider)
    rows = service.overview()
    report += ["## Normalized relationships", table(
        ["Username", "user_follows", "follows_user", "mutual", "source", "source confidence"],
        [(r['account'].username, r['account'].user_follows, r['account'].follows_user,
          r['account'].mutual_follow, r['account'].source, r['account'].source_confidence) for r in rows])]
    coverage_fields = ['following_available', 'followers_available', 'replies_available', 'mentions_available',
                       'likes_received_available', 'reposts_available', 'replies_outbound_available',
                       'mentions_outbound_available', 'likes_performed_available', 'quotes_available']
    report += ["## Coverage", table(["Account", *[k.removesuffix('_available') for k in coverage_fields], "completeness", "confidence", "window"],
        [(r['account'].username, *['AVAILABLE' if getattr(r['metrics'].coverage, k) else 'UNAVAILABLE' for k in coverage_fields],
          r['metrics'].coverage.completeness, r['metrics'].coverage.confidence,
          f"{r['metrics'].coverage.observation_window_start} to {r['metrics'].coverage.observation_window_end}") for r in rows]),
        "Overall coverage is PARTIAL: even high-confidence mock accounts lack likes received/repost/quote coverage. DELTA's missing window stays missing."]
    report += ["## Interaction metrics", table(["Account", "Inbound", "Outbound", "Replies in/out", "Mentions in/out", "Likes in/out", "Reposts in/out", "Last inbound", "Last outbound"],
        [(r['account'].username, m.inbound_interactions, m.outbound_interactions,
          f"{m.replies_to_user}/{m.user_replies_to_them}", f"{m.mentions_of_user}/{m.user_mentions_them}",
          f"{m.likes_of_user}/{m.user_likes_them}", f"{m.reposts_of_user}/{m.user_reposts_them}",
          m.last_inbound_interaction_at, m.last_outbound_interaction_at) for r in rows for m in [r['metrics']]]),
        "None denotes unavailable category data or no observed timestamp, not a measured zero."]
    report += ["## Scores and classifications", table(["Account", "Reciprocity", "Confidence", "Unknown", "Reciprocity reasons", "Value", "Value reasons", "Classification"],
        [(r['account'].username, r['reciprocity'].score, r['reciprocity'].confidence, r['reciprocity'].unknown,
          ', '.join(r['reciprocity'].reason_codes), r['relationship_value'].score,
          ', '.join(r['relationship_value'].reason_codes), r['metrics'].relationship_class) for r in rows])]
    report += ["## Unfollow ranking", table(["Rank", "Account", "Score", "Confidence", "Reciprocity", "Value", "Mutual", "Reasons"],
        [(index, r['account'].username, r['unfollow_candidate'].score, r['unfollow_candidate'].confidence,
          r['reciprocity'].score, r['relationship_value'].score, r['account'].mutual_follow,
          ', '.join(r['unfollow_candidate'].reason_codes)) for index, r in enumerate(service.unfollow_candidates(), 1)]),
        "ALPHA and EPSILON are excluded by eligibility/value rules."]
    report += ["## High-value ranking", table(["Rank", "Account", "Score", "Confidence", "Reasons"],
        [(index, r['account'].username, r['high_value_connection'].score, r['high_value_connection'].confidence,
          ', '.join(r['high_value_connection'].reason_codes)) for index, r in enumerate(service.high_value(), 1)]),
        "Default high-value threshold: 40. BETA's outbound-only effort is insufficient."]
    report += ["## Follow queries", table(["Query", "Results"], [(name, ', '.join(r['account'].username for r in getattr(service, name)()))
               for name in ['following_not_back', 'followers_not_followed', 'mutuals']]),
               "## Never-interact", json_block(service.never_interact())]
    for name in ['BETA', 'DELTA']:
        report += [f"## {name} detail", json_block(service.account_detail(name))]
    report += ["## Observation-window verification", table(["Window", "GAMMA outbound count", "GAMMA unfollow score", "Confidence"],
        [(window, r['metrics'].outbound_interactions, r['unfollow_candidate'].score, r['unfollow_candidate'].confidence)
         for window in ['30d', '90d', '180d', '365d', 'all']
         for r in [AudienceQueryService(provider, window=window).account_detail('GAMMA')]])]
    with tempfile.TemporaryDirectory(prefix='phase7_verification_') as temp:
        root = Path(temp)
        accounts = provider.get_accounts()
        payload = {
            'users': [{'id': a.account_id, 'username': a.username} for a in accounts],
            'following': [{'id': a.account_id, 'username': a.username} for a in accounts if a.user_follows],
            'followers': [{'id': a.account_id, 'username': a.username} for a in accounts if a.follows_user],
            'replies': [{'actor_account_id': i.actor_account_id, 'target_account_id': i.target_account_id,
                         'timestamp': i.timestamp.isoformat(), 'post_id': 'p-' + i.interaction_id} for i in provider.get_interactions()],
            'posts': [{'text': 'Deterministic normalized post', 'timestamp': '2026-06-01T00:00:00Z'}],
            'coverage': asdict(accounts[0].data_coverage),
            'account_coverage': {a.account_id: asdict(a.data_coverage) for a in accounts},
        }
        archive = root / 'normalized.json'
        archive.write_text(json.dumps(payload, default=default), encoding='utf-8')
        with Database(root / 'imports.db') as db:
            ensure_schema(db)
            importer = XArchiveImportService(db)
            first = importer.import_archive(archive); first_counts = counts(db)
            second = importer.import_archive(archive); second_counts = counts(db)
            assert first.interactions == 57 and second.interactions == 0
            report += ['## Import idempotency and persistence', table(['Table', 'Import #1', 'Import #2'],
                       [(name, first_counts[name], second_counts[name]) for name in first_counts]),
                       f'Imported interactions: {first.interactions}, then {second.interactions}. Persisted posts: {first.posts}, then {second.posts}.',
                       'Actual links:', json_block([dict(r) for r in db.execute('SELECT import_run_id,account_id FROM audience_import_run_accounts')]),
                       'Stable hashes:', json_block([dict(r) for r in db.execute('SELECT archive_hash,status FROM audience_import_runs')]),
                       'IDs: canonical SHA-256 for ID-less interactions/posts; accounts and rankings are unique by (account_id, source); interactions by interaction_id; posts by (post_id, source).']
            before, before_state = counts(db), state(db)
            failure = root / 'late.json'
            failure.write_text(json.dumps({'following': [{'id': 'new', 'username': 'NEW'}]}), encoding='utf-8')
            def late_failure(self, **kwargs):
                assert self.database.execute("SELECT 1 FROM audience_accounts WHERE account_id='new'").fetchone()
                assert self.database.execute("SELECT 1 FROM audience_relationships WHERE account_id='new'").fetchone()
                raise RuntimeError('intentional late failure after account/relationship writes')
            with patch.object(AudienceQueryService, 'persist', late_failure):
                try:
                    importer.import_archive(failure)
                except RuntimeError as exc:
                    failure_message = str(exc)
                else:
                    raise AssertionError('Late failure did not occur')
            assert state(db) == before_state
            report += ['## Atomic rollback', failure_message, table(['Table', 'Before', 'After'],
                       [(name, before[name], counts(db)[name]) for name in before]),
                       'All rows and source-selection configuration are identical before/after. No success record or partial import survives.']
            assert [r['account'].username for r in AudienceQueryService(DatabaseXAudienceDataProvider(db)).unfollow_candidates()] == ['BETA', 'GAMMA', 'DELTA']
        native = root / 'native.zip'
        with zipfile.ZipFile(native, 'w') as z:
            for section, rows in [('account', [{'account': {'accountId': 'owner', 'username': 'owner'}}]),
                                  ('following', [{'following': {'accountId': 'alpha'}}]),
                                  ('follower', [{'follower': {'accountId': 'alpha'}}]),
                                  ('tweets', [{'tweet': {'id_str': 'p1', 'full_text': 'hello'}}])]:
                z.writestr('archive/data/' + section + '.js', f'window.YTD.{section}.part0 = {json.dumps(rows)};')
            z.writestr('archive/data/like.js', 'window.YTD.like.part0 = [];')
        compatibility = XArchiveAdapter().inspect(native)
        assert compatibility['status'] == 'INSPECTED_PARTIAL' and not compatibility['native_import_supported']
        report += ['## Synthetic native ZIP compatibility', json_block(compatibility)]
        env = os.environ.copy()
        env['PYTHONPATH'] = str(ROOT / 'src')
        env['EXITVECTOR_DATABASE_URL'] = 'sqlite:///' + str(root / 'cli.db')
        env['AUDIENCE_PROVIDER'] = 'auto'
        env.pop('EXITVECTOR_AUDIENCE_PROVIDER', None)
        matrix = []
        commands = [[], ['--window', '90d'], ['never-interact'], ['low-reciprocity'], ['unfollow-candidates'],
                    ['high-value'], ['following-not-back'], ['followers-not-followed'], ['mutuals'], ['account', '@BETA'],
                    ['import', str(archive)], ['--source', 'database'],
                    ['--source', 'archive', '--archive', str(archive)], ['inspect-archive', str(native)], ['import', str(native)]]
        for args in commands:
            completed = subprocess.run([sys.executable, '-m', 'exitvector_agent', 'audience', *args], cwd=ROOT, env=env, capture_output=True, text=True)
            assert completed.returncode == (2 if args == ['import', str(native)] else 0), completed.stderr + completed.stdout
            result = json.loads(completed.stdout)
            display = 'audience ' + ' '.join(args).replace(str(archive), '<normalized.json>').replace(str(native), '<native.zip>')
            data = result.get('results')
            if isinstance(data, list):
                summary = ', '.join(r.get('username') or r['account']['username'] for r in data)
            elif isinstance(data, dict):
                summary = data['account']['username']
            else:
                summary = result.get('status') or ('UNSUPPORTED' if 'error' in result else f"{result['accounts']} accounts imported")
            matrix.append((display.strip(), completed.returncode, result.get('source', '-'), summary))
        report += ['## CLI command matrix', table(['Command', 'Exit', 'Source', 'Results'], matrix)]
    # Test execution is part of this reproducible verification, not a stale claim.
    report += ['## Fresh test proof']
    for args in [['tests/test_phase7_audience.py', 'tests/test_phase7_remediation.py', '-q'], ['-q']]:
        completed = subprocess.run([sys.executable, '-m', 'pytest', *args], cwd=ROOT, capture_output=True, text=True)
        report += ['`python -m pytest ' + ' '.join(args) + '`', '```text\n' + completed.stdout.strip() + '\n```']
        if completed.returncode:
            raise RuntimeError(completed.stdout + completed.stderr)
        print(completed.stdout.strip().splitlines()[-1])
    report += ['## Files changed', '\n'.join('- `' + name + '`' for name in [
        'src/exitvector_agent/audience.py', 'src/exitvector_agent/audience_data.py', 'src/exitvector_agent/audience_archive.py',
        'src/exitvector_agent/database.py', 'src/exitvector_agent/config.py', 'src/exitvector_agent/__main__.py',
        'tests/test_phase7_remediation.py', 'README.md', 'scripts/verify_phase7.py', 'PHASE7_VERIFICATION.md']),
        'Original Phase 7 tests are unchanged. No Phase 8, API, browser, scraping, or automatic follow/unfollow features were added. No commit, push, or deployment was performed.',
        '## Remaining compatibility limit',
        'Normalized JSON import and database analysis work. Native ZIP archives can be safely inspected and previewed, but native import remains explicitly UNSUPPORTED. A real archive can be provided for compatibility inspection, not for guaranteed direct import.']
    target = ROOT / 'PHASE7_VERIFICATION.md'
    target.write_text('\n\n'.join(report) + '\n', encoding='utf-8')
    print(target)


if __name__ == '__main__':
    main()
